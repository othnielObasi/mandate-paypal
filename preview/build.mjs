// Builds dist/mandate-preview.html: the real Mandate UI and API handlers in one self-contained file.
// Usage: npm run preview:html
import { build } from "esbuild";
import { readdirSync, statSync, writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist");
mkdirSync(out, { recursive: true });

// 1. Route table from app/api/**/route.ts
const routes = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name === "route.ts") routes.push(p);
  }
})(join(root, "app/api"));
routes.sort();
const gen = routes
  .map((p, i) => `import * as r${i} from "../${relative(root, p).replace(/\\/g, "/").replace(/\.ts$/, "")}";`)
  .concat(
    "export const ROUTES = [",
    ...routes.map((p, i) => `  { pattern: "/${relative(join(root, "app"), dirname(p)).replace(/\\/g, "/")}", mod: r${i} },`),
    "];",
  )
  .join("\n");
writeFileSync(join(root, "preview/routes.generated.ts"), `// Generated by preview/build.mjs. Do not edit.\n${gen}\n`);

// 2. Bundle
const shim = (f) => join(root, "preview/shims", f);
const result = await build({
  entryPoints: [join(root, "preview/main.tsx")],
  bundle: true,
  write: false,
  outdir: out,
  format: "iife",
  platform: "browser",
  target: ["es2022", "safari16"],
  minify: true,
  legalComments: "none",
  jsx: "automatic",
  loader: { ".woff2": "dataurl", ".woff": "dataurl" },
  alias: {
    "@": root,
    "node:crypto": shim("node-crypto.ts"),
    crypto: shim("node-crypto.ts"),
    "next/link": shim("next-link.tsx"),
    "next/navigation": shim("next-navigation.ts"),
    "@paypal/agent-toolkit/ai-sdk": shim("server-only.ts"),
    pg: shim("server-only.ts"),
    buffer: shim("buffer.ts"),
    "node:buffer": shim("buffer.ts"),
  },
  inject: [join(root, "preview/globals.ts")],
  define: {
    "process.env.NODE_ENV": '"production"',
  },
  logLevel: "warning",
});

const js = result.outputFiles.find((f) => f.path.endsWith(".js")).text.replace(/<\/script/gi, "<\\/script");
const css = result.outputFiles.find((f) => f.path.endsWith(".css"))?.text ?? "";
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="Mandate turns one sentence into signed spending rules that every AI agent must obey, then pays with PayPal only when the rules say yes.">
<meta name="generator" content="mandate ${pkg.version} preview">
<title>Mandate · Let AI shop for you, on your terms</title>
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 28 28'%3E%3Crect x='1' y='1' width='26' height='26' rx='8' fill='%231E40AF'/%3E%3Cpath d='M8 14.5l4 4 8-9' stroke='white' stroke-width='2.4' fill='none' stroke-linecap='round' stroke-linejoin='round'/%3E%3C/svg%3E">
<style>${css}</style>
</head>
<body>
<div id="root"></div>
<noscript>Mandate needs JavaScript to run.</noscript>
<script>${js}</script>
</body>
</html>
`;
const file = join(out, "mandate-preview.html");
writeFileSync(file, html);
console.log(`${relative(root, file)}  ${(html.length / 1024 / 1024).toFixed(2)} MB  (${routes.length} API routes)`);
