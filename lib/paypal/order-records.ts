import { ApiError, Client, Environment, OrdersController } from "@paypal/paypal-server-sdk";

/** What PayPal itself says about an order: the record a seller or reviewer trusts. */
export interface PayPalOrderRecord {
  status: string;
  currency: string;
  amountMinor: number;
  captureIds: string[];
}

/** Reads PayPal's own record of an order, independently of Mandate's database. */
export interface OrderRecords {
  readonly source: string;
  /** null when PayPal has no such order. */
  getOrderRecord(paypalOrderId: string): Promise<PayPalOrderRecord | null>;
}

const toMinor = (value: string | undefined) => {
  const n = Number(value);
  return Number.isFinite(n) ? Math.round(n * 100) : NaN;
};

type GetOrder = Pick<OrdersController, "getOrder">;

/**
 * PayPal's Server SDK (@paypal/paypal-server-sdk, generated by APIMatic from PayPal's API
 * definitions). Used read-only by the seller check: the payment is confirmed against PayPal's
 * order record, not only against what Mandate stored.
 */
export class ServerSdkOrderRecords implements OrderRecords {
  readonly source = "PayPal Server SDK";

  constructor(private orders: GetOrder) {}

  static sandbox(o: { clientId: string; clientSecret: string; timeoutMs?: number }) {
    const client = new Client({
      clientCredentialsAuthCredentials: { oAuthClientId: o.clientId, oAuthClientSecret: o.clientSecret },
      environment: Environment.Sandbox,
      timeout: o.timeoutMs ?? 10_000,
    });
    return new ServerSdkOrderRecords(new OrdersController(client));
  }

  async getOrderRecord(paypalOrderId: string): Promise<PayPalOrderRecord | null> {
    try {
      const { result: order } = await this.orders.getOrder({ id: paypalOrderId });
      const units = order.purchaseUnits ?? [];
      const currencies = new Set(units.map((u) => u.amount?.currencyCode).filter(Boolean));
      return {
        status: String(order.status ?? "UNKNOWN"),
        currency: currencies.size === 1 ? [...currencies][0]! : "MIXED",
        amountMinor: units.reduce((s, u) => s + toMinor(u.amount?.value), 0),
        captureIds: units.flatMap((u) => (u.payments?.captures ?? []).filter((c) => c.status === "COMPLETED" && c.id).map((c) => c.id!)),
      };
    } catch (e) {
      if (e instanceof ApiError && e.statusCode === 404) return null;
      throw e;
    }
  }
}
